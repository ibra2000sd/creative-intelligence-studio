#!/usr/bin/env node
// Writes docs/cli.md from the CLI's own help output, so the reference cannot drift from the code.
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const run = (...args) => spawnSync(process.execPath, [path.join(REPO, 'plugin/bin/creative-studio'), ...args], { encoding: 'utf8' }).stdout;
const overview = run('help');
const groups = [];
for (const line of overview.split('\n')) {
  const g = /^(\w[\w ]+):$/.exec(line);
  const c = /^\s{2}(\S+)\s{2,}(.+)$/.exec(line);
  if (g) groups.push({ name: g[1], commands: [] });
  else if (c && groups.length) groups.at(-1).commands.push({ name: c[1], summary: c[2] });
}
let md = `# Command reference\n\nGenerated by \`node scripts/gen-cli-docs.mjs\` from \`creative-studio help\`. Do not edit by hand.\n\nThe command is \`creative-studio\`. Inside Claude Code it is on the PATH while the plugin is enabled; from a checkout of this repository use \`node plugin/bin/creative-studio\` or \`pnpm cs\`.\n\nMost commands accept \`--json\` for machine-readable output and \`--project <dir>\` to act on a project other than the current directory.\n\n**Exit codes:** 0 success; 1 failed (a check failed or input was invalid); 2 usage error; 3 blocked by an approval gate, a handoff contract, a policy or a budget; 4 an optional engine is not installed.\n\n| Command | Purpose |\n|---|---|\n`;
for (const g of groups) for (const c of g.commands) md += `| [\`${c.name}\`](#${c.name}) | ${c.summary} |\n`;
for (const g of groups) {
  md += `\n## ${g.name}\n`;
  for (const c of g.commands) {
    const help = run('help', c.name).trim().split('\n');
    md += `\n### ${c.name}\n\n${c.summary}.\n\n\`\`\`text\n${help.slice(2).join('\n').trim()}\n\`\`\`\n`;
  }
}
fs.writeFileSync(path.join(REPO, 'docs/cli.md'), md);
console.log(`docs/cli.md: ${groups.reduce((n, g) => n + g.commands.length, 0)} commands in ${groups.length} groups`);
