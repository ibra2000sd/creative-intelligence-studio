// Production scaffolding: marketing website, web application, mobile app and
// 3D scene. "scaffold" copies a template once and never overwrites your edits;
// "sync" regenerates only the files derived from the Experience DNA and the
// asset registry, which is how a DNA revision reaches every deliverable.
