const MIME = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.mjs': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8', '.json': 'application/json; charset=utf-8', '.svg': 'image/svg+xml', '.png': 'image/png', '.jpg': 'image/jpeg', '.webp': 'image/webp', '.avif': 'image/avif', '.woff2': 'font/woff2', '.woff': 'font/woff', '.ttf': 'font/ttf', '.glb': 'model/gltf-binary', '.wasm': 'application/wasm', '.ico': 'image/x-icon', '.txt': 'text/plain; charset=utf-8', '.map': 'application/json', '.pdf': 'application/pdf', '.hbc': 'application/octet-stream' };

/** Static server for built output. Serves only files inside `dir`; binds to loopback. */
export function serve(dir, { port = 0, spa = false } = {}) {
  const rootDir = fs.realpathSync(path.resolve(dir));
  const server = http.createServer((req, res) => {
    let pathname;
    try {
      pathname = decodeURIComponent(new URL(req.url, 'http://localhost').pathname);
    } catch {
      res.writeHead(400).end('Bad request');
      return;
    }
    let file = path.join(rootDir, pathname);
    if (file !== rootDir && !file.startsWith(rootDir + path.sep)) {
      res.writeHead(403).end('Forbidden');
      return;
    }
    if (exists(file) && fs.statSync(file).isDirectory()) file = path.join(file, 'index.html');
    if (!exists(file) && spa && !path.extname(pathname)) file = path.join(rootDir, 'index.html');
    if (!exists(file)) {
      res.writeHead(404, { 'content-type': 'text/plain' }).end('Not found');
      return;
    }
    const hashed = /[.-][A-Za-z0-9_-]{8,}\.(js|css|woff2?|webp|avif|png|svg)$/.test(file);
    res.writeHead(200, { 'content-type': MIME[path.extname(file).toLowerCase()] || 'application/octet-stream', 'cache-control': hashed ? 'public, max-age=31536000, immutable' : 'no-cache', 'x-content-type-options': 'nosniff' });
    fs.createReadStream(file).pipe(res);
  });
  return new Promise((resolve, reject) => {
    server.once('error', reject);
    server.listen(port, '127.0.0.1', () => resolve({ server, port: server.address().port, url: `http://127.0.0.1:${server.address().port}`, close: () => new Promise((r) => server.close(r)) }));
  });
}

async function preview({ _, flags }) {
  const dir = path.resolve(_[0] || 'dist');
  if (!exists(dir)) throw new CisError('E_READ', `Nothing to preview at ${dir}. Build the project first.`);
  const s = await serve(dir, { port: Number(flags.port || 4173), spa: Boolean(flags.spa) });
  print(`Serving ${dir} at ${s.url} (loopback only). Press Ctrl+C to stop.`);
  await new Promise((resolve) => process.once('SIGINT', resolve));
  await s.close();
}

